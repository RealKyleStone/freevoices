const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');

test('credits and refunds retain the original payment and reconcile separately', { skip: !process.env.FREEVOICES_TEST_API_URL || process.env.INVOICE_ADJUSTMENTS_ENABLED !== 'true', timeout:30000 }, async t => {
  const { executeQuery:q, closePool } = require('../src/services/db.service');
  const { todayIso } = require('../src/services/document-math');
  let uid,otherUid;
  t.after(async()=>{
    try { if (uid) {
      await q('DELETE FROM payment_refunds WHERE user_id=?',[uid]);
      await q('DELETE FROM credit_notes WHERE user_id=?',[uid]);
      await q('DELETE FROM documents WHERE user_id=?',[uid]);
      await q('DELETE FROM customers WHERE user_id=?',[uid]);
      await q('DELETE FROM sessions WHERE userId=?',[uid]);
      await q('DELETE FROM users WHERE id=?',[uid]);
    }
      if (otherUid) { await q('DELETE FROM sessions WHERE userId=?',[otherUid]); await q('DELETE FROM users WHERE id=?',[otherUid]); }
    } finally { await closePool(); }
  });
  uid=(await q('INSERT INTO users(email,company_name) VALUES(?,?)',[`adjust-${randomUUID()}@example.test`,'Test seller'])).insertId;
  const auth=randomUUID();
  await q('INSERT INTO sessions(userId,token,expires) VALUES(?,?,DATE_ADD(NOW(),INTERVAL 1 HOUR))',[uid,createHash('sha256').update(auth).digest('hex')]);
  const base=process.env.FREEVOICES_TEST_API_URL.replace(/\/$/,'');
  const request=async(route,method='GET',body)=>{const response=await fetch(base+route,{method,headers:{Authorization:`Bearer ${auth}`,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});return {status:response.status,data:response.headers.get('content-type')?.includes('application/pdf')?Buffer.from(await response.arrayBuffer()):await response.json()};};
  otherUid=(await q('INSERT INTO users(email,company_name) VALUES(?,?)',[`other-${randomUUID()}@example.test`,'Other seller'])).insertId;
  const otherToken=randomUUID();
  await q('INSERT INTO sessions(userId,token,expires) VALUES(?,?,DATE_ADD(NOW(),INTERVAL 1 HOUR))',[otherUid,createHash('sha256').update(otherToken).digest('hex')]);
  const otherRequest=async(route,method='GET',body)=>{const response=await fetch(base+route,{method,headers:{Authorization:`Bearer ${otherToken}`,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});return response.status;};
  const ok=async(...args)=>{const r=await request(...args);assert.ok(r.status<300,`${args[0]}: ${r.status} ${JSON.stringify(r.data)}`);return r.data;};
  const customer=await ok('/customers','POST',{name:'Adjustment buyer',email:'adjust@example.test',billing_address:'Road'});
  const currency=(await q("SELECT id FROM currencies WHERE code='ZAR'"))[0].id;
  const invoice=await ok('/invoices','POST',{customer_id:customer.id,currency_id:currency,issue_date:todayIso(),items:[{description:'Work',quantity:1,unit_price:100,vat_rate:15}]});
  assert.equal((await request(`/invoices/${invoice.id}/pdf?markSent=true`)).status,200);
  await ok(`/invoices/${invoice.id}/mark-paid`,'POST',{amount:115,payment_date:todayIso(),payment_method:'BANK_TRANSFER'});
  const [payment]=await q('SELECT id,amount FROM payments WHERE document_id=?',[invoice.id]);
  assert.equal(await otherRequest(`/invoices/${invoice.id}/adjustments`),404);
  assert.equal(await otherRequest(`/invoices/${invoice.id}/payments/${payment.id}/receipt`),404);
  assert.equal(await otherRequest(`/invoices/${invoice.id}/credit-notes`,'POST',{request_key:randomUUID(),subtotal:1,vat_amount:0,total:1,reason:'No',description:'No'}),404);
  assert.equal(await otherRequest(`/invoices/${invoice.id}/refunds`,'POST',{request_key:randomUUID(),payment_id:payment.id,amount:1,refund_date:todayIso(),method:'BANK_TRANSFER',reason:'No'}),404);
  const paymentReceipt=await request(`/invoices/${invoice.id}/payments/${payment.id}/receipt`);
  assert.equal(paymentReceipt.status,200);
  assert.equal(paymentReceipt.data.subarray(0,4).toString(),'%PDF');
  assert.equal((await fetch(`${base}/invoices/${invoice.id}/payments/${payment.id}/receipt`)).status,401);
  assert.equal((await request(`/invoices/${invoice.id}/payments/999999999/receipt`)).status,404);
  const creditPayload={request_key:randomUUID(),subtotal:40,vat_amount:6,total:46,reason:'Reduced scope',description:'Service adjustment'};
  const credit=await ok(`/invoices/${invoice.id}/credit-notes`,'POST',creditPayload);
  assert.match(credit.document_number,/^CN-\d{8}$/);
  const replay=await ok(`/invoices/${invoice.id}/credit-notes`,'POST',creditPayload);
  assert.equal(replay.document_number,credit.document_number);
  assert.equal(replay.replayed,true);
  const pdf=await request(`/invoices/${invoice.id}/credit-notes/${credit.id}/pdf`);
  assert.equal(pdf.status,200);
  assert.equal(pdf.data.subarray(0,4).toString(),'%PDF');
  assert.equal(credit.summary.refundDue,46);
  assert.equal((await request(`/invoices/${invoice.id}/credit-notes`,'POST',{request_key:randomUUID(),subtotal:61,vat_amount:9,total:70,reason:'Excess',description:'Excess'})).status,422);
  const refundPayload={request_key:randomUUID(),payment_id:payment.id,amount:46,refund_date:todayIso(),method:'BANK_TRANSFER',reference:'RETURN-1',reason:'Credit paid back'};
  const refund=await ok(`/invoices/${invoice.id}/refunds`,'POST',refundPayload);
  assert.equal((await ok(`/invoices/${invoice.id}/refunds`,'POST',refundPayload)).replayed,true);
  assert.equal(refund.summary.refundDue,0);
  assert.equal(refund.summary.balanceDue,0);
  assert.equal((await request(`/invoices/${invoice.id}/refunds`,'POST',{request_key:randomUUID(),payment_id:payment.id,amount:70,refund_date:todayIso(),method:'BANK_TRANSFER',reason:'Excess'})).status,422);
  const record=await ok(`/invoices/${invoice.id}/adjustments`);
  assert.equal(record.credits.length,1);
  assert.equal(record.refunds.length,1);
  assert.equal(record.refunds[0].reference,'RETURN-1');
  assert.match((await q('SELECT reference FROM payment_refunds WHERE id=?',[refund.id]))[0].reference,/^fv1\./);
  const events=await q("SELECT event_type,COUNT(*) AS count FROM document_tracking WHERE document_id=? AND event_type IN ('CREDIT_NOTE','REFUND') GROUP BY event_type",[invoice.id]);
  assert.deepEqual(Object.fromEntries(events.map(row=>[row.event_type,row.count])),{CREDIT_NOTE:1,REFUND:1});
  const detail=await ok(`/invoices/${invoice.id}`);
  assert.equal(detail.adjusted_total,'69.00');
  assert.equal(detail.balance_due,'0.00');
  assert.equal(detail.credit_total,'46.00');
  const statement=await ok(`/reports/customer-statement?currency=ZAR&customer_id=${customer.id}&from=${todayIso()}&to=${todayIso()}`);
  assert.deepEqual(statement.rows.map(row=>row.kind),['INVOICE','PAYMENT','CREDIT_NOTE','REFUND']);
  assert.equal(statement.closing_balance,0);
  const vat=await ok('/reports/vat-summary?currency=ZAR');
  const month=todayIso().slice(0,7);
  assert.equal(Number(vat.find(row=>row.month===month).vat_amount),9);
  const revenue=await ok('/reports/revenue-by-month?currency=ZAR');
  assert.equal(Number(revenue.find(row=>row.month===month).revenue),69);
  const ledger=await ok(`/reports/payments-ledger?currency=ZAR&customer_id=${customer.id}&from=${todayIso()}&to=${todayIso()}`);
  assert.deepEqual(ledger.rows.map(row=>row.kind),['PAYMENT','REFUND']);
  assert.equal(ledger.rows.reduce((sum,row)=>sum+Number(row.amount),0),69);
  assert.equal(Number((await q('SELECT amount FROM payments WHERE id=?',[payment.id]))[0].amount),115);
  const simultaneous={request_key:randomUUID(),subtotal:10,vat_amount:1.5,total:11.5,reason:'Further reduction',description:'Additional service adjustment'};
  const attempts=await Promise.all([request(`/invoices/${invoice.id}/credit-notes`,'POST',simultaneous),request(`/invoices/${invoice.id}/credit-notes`,'POST',simultaneous)]);
  assert.deepEqual(attempts.map(attempt=>attempt.status).sort(),[200,201]);
  assert.equal((await q('SELECT COUNT(*) AS count FROM credit_notes WHERE invoice_id=?',[invoice.id]))[0].count,2);

  const fullyCredited=await ok('/invoices','POST',{customer_id:customer.id,currency_id:currency,issue_date:todayIso(),items:[{description:'Cancelled work',quantity:1,unit_price:100,vat_rate:0}]});
  assert.equal((await request(`/invoices/${fullyCredited.id}/pdf?markSent=true`)).status,200);
  await ok(`/invoices/${fullyCredited.id}/credit-notes`,'POST',{request_key:randomUUID(),subtotal:100,vat_amount:0,total:100,reason:'Work not supplied',description:'Full reversal'});
  const creditedDetail=await ok(`/invoices/${fullyCredited.id}`);
  assert.equal(creditedDetail.status,'CREDITED');
  assert.equal(creditedDetail.balance_due,'0.00');
  const share=await ok(`/invoices/${fullyCredited.id}/share`,'POST',{});
  const portalResponse=await fetch(`${base}/public/invoice/${share.share_url.split('/').pop()}`);
  assert.equal(portalResponse.status,200);
  const portal=await portalResponse.json();
  assert.equal(portal.balance_due,'0.00');
  assert.equal(portal.credit_total,'100.00');
  assert.equal((await request(`/invoices/${fullyCredited.id}/receipt`)).status,400);
  assert.equal((await request(`/invoices/${fullyCredited.id}/mark-paid`,'POST',{amount:1,payment_date:todayIso(),payment_method:'BANK_TRANSFER'})).status,400);
});
