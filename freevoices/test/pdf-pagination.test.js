const test = require('node:test');
const assert = require('node:assert/strict');
const { inflateSync } = require('node:zlib');
const { buildInvoicePdf, buildQuotePdf, buildReceiptPdf } = require('../src/services/pdf.service');

// Read PDFKit's actual output streams, rather than testing a mock renderer.
function pages(buffer) {
  const raw = buffer.toString('latin1');
  const result = [];
  const streams = /<<[^>]*\/Length (\d+)[^>]*>>\s*stream\r?\n/g;
  for (const match of raw.matchAll(streams)) {
    if (!match[0].includes('/FlateDecode')) continue;
    const start = match.index + match[0].length;
    const content = inflateSync(buffer.subarray(start, start + Number(match[1]))).toString();
    result.push([...content.matchAll(/<([0-9a-f]+)>/gi)]
      .map(m => Buffer.from(m[1], 'hex').toString('latin1')).join(''));
  }
  assert.equal(result.length, [...raw.matchAll(/\/Type \/Page\b/g)].length);
  return result;
}

const user = { company_name: 'Pagination Test Business', email: 'pdf@example.test',
  bank_name: 'Test Bank', bank_account_number: '123456', bank_branch_code: '000000' };
const base = { document_number: 'INV-2026-0001', customer_name: 'PDF Test Customer',
  customer_email: 'customer@example.test', customer_billing_address: '1 Test Street',
  issue_date: '2026-10-24', due_date: '2026-11-23', valid_until: '2026-11-23',
  payment_terms: 30, currency_symbol: 'R', subtotal: 6000, vat_amount: 900, total: 6900 };

for (const [kind, build] of [['invoice', buildInvoicePdf], ['quote', buildQuotePdf], ['receipt', buildReceiptPdf]]) {
  for (const count of [1, 20, 60, 200]) {
    test(`${kind}: ${count} rows retain every item with repeated headings and numbered footers`, async () => {
      const items = Array.from({ length: count }, (_, i) => ({
        description: `ITEM${String(i).padStart(4, '0')} Consulting implementation and support for the evaluation project.`,
        quantity: 1, unit_price: 100, vat_rate: 15, total: 115,
      }));
      const output = pages(await build({ ...base, notes: 'ENDOFNOTES' }, items, user,
        [{ payment_date: '2026-10-24', payment_method: 'BANK_TRANSFER', amount: 6900, transaction_reference: 'PAYMENTREF' }]));
      assert.ok(output.length <= Math.ceil(count / 12) + 1, `Unexpected ${output.length} pages`);
      if (count === 1) assert.equal(output.length, 1, 'A footer must not create a blank second page');
      const all = output.join('');
      assert.equal(all.replace(/\s/g, '').split('R100,00').length - 1, count, 'Every row retains its unit price');
      for (let i = 0; i < count; i++) {
        const marker = `ITEM${String(i).padStart(4, '0')}`;
        assert.equal(all.split(marker).length - 1, 1, marker);
      }
      for (const [i, page] of output.entries()) {
        assert.ok(page.includes('Generated by FreeVoices'), `Missing footer on page ${i + 1}`);
        assert.ok(page.includes(`${i + 1} / ${output.length}`), 'Missing page count');
        if (page.includes('ITEM')) assert.ok(page.includes('DESCRIPTION'), 'Missing table heading');
      }
      if (kind !== 'receipt') assert.ok(all.includes('ENDOFNOTES'));
      else assert.ok(all.includes('PAYMENTREF'));
      assert.ok(all.replace(/\s/g, '').includes('6900,00'), 'Missing final total');
    });
  }
  test(`${kind}: a description taller than a page and long notes retain their ending`, async () => {
    const items = [{ description: `DESCRIPTIONSTART ${'Long item description. '.repeat(1000)} DESCRIPTIONEND`,
      quantity: 1, unit_price: 100, vat_rate: 15, total: 115 }];
    const output = pages(await build({ ...base,
      notes: `${'Long note text. '.repeat(1500)} NOTESEND`,
      terms_conditions: `${'Terms paragraph. '.repeat(1000)} TERMSEND`,
    }, items, user, [{ payment_date: '2026-10-24', payment_method: 'BANK_TRANSFER', amount: 6900,
      transaction_reference: `${'Long payment reference '.repeat(500)} PAYMENTEND` }]));
    const all = output.join('');
    for (const marker of ['DESCRIPTIONSTART', 'DESCRIPTIONEND', ...(kind === 'receipt' ? ['PAYMENTEND'] : ['NOTESEND', 'TERMSEND'])]) {
      assert.equal(all.split(marker).length - 1, 1, marker);
    }
    assert.ok(output.length < 40, `Unexpected ${output.length} pages`);
  });
}
